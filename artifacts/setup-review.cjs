const { chromium } = require('playwright');
const { strict: assert } = require('node:assert');
(async () => {
  const browser = await chromium.launch({ channel: 'msedge' });
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
    await page.goto('http://localhost:3000/setup-review');
    await page.getByRole('heading', { name: 'Product Demo', exact: true }).waitFor();
    await page.evaluate(() => document.fonts.ready);
    await page.screenshot({ path: 'artifacts/setup-desktop.png', fullPage: true });
    await page.getByLabel('App link', { exact: true }).fill('https://example.com');
    await page.getByRole('button', { name: 'Fetch', exact: true }).click();
    assert.equal(await page.getByLabel('Test result').textContent(), 'https://example.com/');
    await page.getByLabel('App name', { exact: true }).fill('Review app');
    await page.getByLabel('Feature to highlight', { exact: true }).fill('Review feature');
    await page.getByRole('radio', { name: 'Marker', exact: true }).focus(); await page.keyboard.press('Space');
    assert.equal(await page.locator('.rw-demo-caption.rw-caption--marker').count(), 1);
    await page.getByRole('button', { name: '1:1', exact: true }).click();
    const box = await page.locator('.rw-demo-phone').boundingBox();
    assert.ok(Math.abs(box.width - box.height) < 1);
    await page.getByRole('button', { name: 'Play preview', exact: true }).click();
    await page.getByRole('button', { name: 'Pause preview', exact: true }).waitFor();
    await page.waitForFunction(() => document.querySelector('[aria-label="Preview playback"]').getAttribute('aria-valuenow') !== '0');
    await page.getByRole('button', { name: 'Pause preview', exact: true }).click();
    await page.getByRole('button', { name: 'Play Ava', exact: true }).click();
    assert.equal(await page.getByLabel('Test result').textContent(), 'ava');
    await page.getByRole('radio', { name: 'Send me the files', exact: true }).focus(); await page.keyboard.press('Space');
    await page.getByRole('button', { name: 'Twice a day', exact: true }).click();
    await page.getByText('14 videos a week', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Sunday', exact: true }).click();
    await page.getByText('12 videos a week', { exact: true }).waitFor();
    await page.getByLabel('Add screenshots or recordings', { exact: true }).setInputFiles({ name: 'review.png', mimeType: 'image/png', buffer: Buffer.from('test fixture') });
    assert.equal(await page.getByLabel('Test result').textContent(), 'review.png');
    await page.getByRole('button', { name: 'Create my videos', exact: true }).click();
    const result = JSON.parse(await page.getByLabel('Test result').textContent());
    assert.equal(result.appName, 'Review app');
    assert.equal(result.captionStyleId, 'marker');
    assert.equal(result.delivery, 'files');
    assert.equal(result.days.length, 6);
    assert.equal(result.postsPerDay, 2);
    assert.equal(result.aspectRatio, '1:1');
    assert.deepEqual(result.platformIds, []);
    await page.getByLabel('Create status', { exact: true }).selectOption('running');
    assert.equal(await page.getByLabel('App name', { exact: true }).isDisabled(), true);
    await page.getByLabel('Create status', { exact: true }).selectOption('error');
    await page.getByText('Could not create your videos. Please try again.').waitFor();
    await page.getByLabel('Fetch status', { exact: true }).selectOption('error');
    await page.getByText('Could not fetch app details.').waitFor();
    await page.getByLabel('Screen status', { exact: true }).selectOption('running');
    await page.locator('.rw-setup-skeleton').first().waitFor();
    await page.getByLabel('Screen status', { exact: true }).selectOption('error');
    await page.getByText('Setup could not be loaded.').waitFor();
    await page.reload();
    await page.setViewportSize({ width: 375, height: 800 });
    await page.getByRole('heading', { name: 'Product Demo', exact: true }).waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 375);
    await page.screenshot({ path: 'artifacts/setup-mobile.png', fullPage: true });
    assert.equal(await page.getByRole('checkbox', { name: 'YouTube Not connected' }).isDisabled(), true);
    console.log('PASS: fetch/upload/voice/create callbacks, complete payload, captions, ratios, preview play/pause, posting frequency/day toggles, loading/error states, disconnected platforms, 375px overflow.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
